const DAY_MS = 86400000;
const shiftIso = (iso, d) => new Date(Date.parse(iso) + d * DAY_MS).toISOString();
const shiftDay = (day, d) => shiftIso(`${day}T00:00:00Z`, d).slice(0, 10);

function assertClean() {
  const out = execFileSync('git', ['status', '--porcelain', ...WATCHED], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
  }).trim();
  if (out) {
    throw new Error(
      `market data is already modified — commit or restore first so the rollback is unambiguous:\n${out}`
    );
  }
}

const snapshot = () => ({
  ...Object.fromEntries(
    fs.readdirSync(SHARED).map((f) => [f, fs.readFileSync(path.join(SHARED, f))])
  ),
  ...Object.fromEntries(PUBLISHED.map((f) => [DATA_KEY(f), fs.readFileSync(f)])),
});

const restore = (snap) => {
  // A scenario may CREATE a file (E writes the attempts ledger): remove what
  // was not there, or it leaks into the next scenario and dirties the tree.
  for (const f of fs.readdirSync(SHARED)) if (!(f in snap)) fs.rmSync(path.join(SHARED, f));
  for (const [f, buf] of Object.entries(snap))
    fs.writeFileSync(f.startsWith('\u0000') ? f.slice(1) : path.join(SHARED, f), buf);
};

/**
 * Roll every monthly series `n` months on, each a large move (`factor` per
 * month), the way Monday's run would leave them. The values are deliberately
 * extreme: a test that only passes for this month's prices — a band on a moving
 * number, a bounded month count — fails here before a real month-roll fails it on
 * a Monday (5.478).
 *
 * BTC is appended directly, as `run.mjs --append-btc` does. Every other series
 * goes through the REAL path (plan 5.760 increment 2): a store is built from the
 * committed series plus the new months, and `publish.mjs` writes prices, FX and
 * the manifest from it, so its rules (every series has the month; bars hold
 * their close; nothing published is removed) run here too.
 */
function rollMonths(n, factor) {
  const data = JSON.parse(fs.readFileSync(MONTHLY, 'utf8'));
  const nextYm = (ym) => {
    const [y, m] = ym.split('-').map(Number);
    return new Date(Date.UTC(y, m, 1)).toISOString().slice(0, 10);
  };
  const btc = data.BTC;
  for (let i = 0; i < n; i++) {
    const last = btc.months[btc.months.length - 1];
    const close = last.close * factor;
    btc.months.push({
      ym: nextYm(last.ym),
      open: last.close,
      high: Math.max(last.close, close) * 1.02,
      low: Math.min(last.close, close) * 0.98,
      close,
    });
  }
  fs.writeFileSync(MONTHLY, `${JSON.stringify(data, null, 2)}\n`);

  const fx = JSON.parse(fs.readFileSync(path.join(DATA_DIR, PUBLISHED_FILES.fx), 'utf8'));
  const store = fs.mkdtempSync(path.join(os.tmpdir(), 'sim-store-'));
  try {
    fs.mkdirSync(path.join(store, 'derived', 'monthly'), { recursive: true });
    fs.mkdirSync(path.join(store, 'daily'));
    const write = (id, rows) => {
      const ym = (r) => r.ym.slice(0, 7);
      const body = rows.map(
        (r) =>
          `${ym(r)},${r.open},${r.high},${r.low},${r.close},${r.tr ?? ''},0,${lastWeekday(ym(r))}`
      );
      fs.writeFileSync(
        path.join(store, 'derived', 'monthly', `${id}.csv`),
        `ym,open,high,low,close,tr_close,distributions,last_day\n${body.join('\n')}\n`
      );
      const lastDay = lastWeekday(ym(rows.at(-1)));
      fs.writeFileSync(
        path.join(store, 'daily', `${id}.csv`),
        `date,open,high,low,close,source\n${lastDay},,,,${rows.at(-1).close},simulator\n`
      );
    };
    for (const [code, s] of Object.entries(PRICE_SERIES)) {
      const rows = data[code].months.map((r) => ({
        ym: r.ym,
        open: r.open,
        high: r.high,
        low: r.low,
        close: r.closePriceOnly ?? r.close,
        tr: s.totalReturn ? r.close : undefined,
      }));
      for (let i = 0; i < n; i++) {
        const last = rows.at(-1);
        const close = last.close * factor;
        rows.push({
          ym: nextYm(last.ym),
          open: last.close,
          high: Math.max(last.close, close) * 1.02,
          low: Math.min(last.close, close) * 0.98,
          close,
          tr: s.totalReturn ? last.tr * factor : undefined,
        });
      }
      write(s.store, rows);
    }
    for (const [code, s] of Object.entries(FX_SERIES)) {
      const v = (r) => (s.usdPerLocal ? r.closeUsdPerLocal : r.closeLocalPerUsd);
      const rows = fx[code].months.map((r) => ({
        ym: r.ym,
        open: v(r),
        high: v(r),
        low: v(r),
        close: v(r),
      }));
      for (let i = 0; i < n; i++) rows.push({ ...rows.at(-1), ym: nextYm(rows.at(-1).ym) });
      write(s.store, rows);
    }
    const quiet = console.log;
    console.log = () => {};
    let code;
    try {
      code = publish(['--store', store, '--store-commit', '0'.repeat(40), '--out', DATA_DIR]);
    } finally {
      console.log = quiet;
    }
    if (code !== 0) throw new Error(`publish.mjs refused the rolled store (exit ${code})`);
  } finally {
    fs.rmSync(store, { recursive: true, force: true });
  }
}

/**
 * Move the world on by one cycle, the way a real run leaves it.
 * @param {{ days: number, etfDays: number | null, etfIncomplete?: boolean }} opts
 *   etfDays = how far the new ETF anchor moves past the latest record (null =
 *   the ETF leg failed: nothing collected); etfIncomplete = the pull came back
 *   without share counts and goes through the real refusal (scenario E)
 */
function advance({
  days,
  etfDays,
  etfIncomplete = false,
  btcRoll = false,
  correction = false,
  m2Stale = false,
}) {
  const p = (f) => path.join(SHARED, f);
  const computed = JSON.parse(fs.readFileSync(p('computed.json'), 'utf8'));
  computed.computed_at = shiftIso(computed.computed_at, days);
  // 5.860 (scenario H): the month Bitcoin's confirmed candle rolls. The candle is appended
  // as `run.mjs --append-btc` leaves it, and BTC-01..04 are recomputed by the real engine
  // (evaluateBtcStructure throws if the expected month is missing, as on the real run).
  if (btcRoll) {
    const data = JSON.parse(fs.readFileSync(MONTHLY, 'utf8'));
    const last = data.BTC.months.at(-1);
    const ym = nextMonthYM(last.ym);
    if (ym !== expectedConfirmedMonthYM(new Date(computed.computed_at)))
      throw new Error(`scenario clock does not roll Bitcoin to ${ym}`);
    const close = last.close * 1.08;
    data.BTC.months.push({
      ym,
      open: last.close,
      high: close * 1.03,
      low: last.close * 0.95,
      close,
    });
    fs.writeFileSync(MONTHLY, `${JSON.stringify(data, null, 2)}\n`);
    const fresh = archiveSignals(
      evaluateBtcStructure(data.BTC.months, new Date(computed.computed_at)),
      {
        etfSnapshotCount: 0,
      }
    );
    computed.signals = computed.signals.map((s) => fresh.find((f) => f.id === s.id) ?? s);
  }
  // Scenario I: a same-day re-run that CORRECTS the first (a different score), so the check that
  // the day's chart point follows the LAST run of the day can fail (SNAP-IMMUT-1, runDayIndex).
  if (correction) {
    // A revised Friday dollar close (the source corrected it), moved across its 20-week EMA, and
    // the state, values, detail and points rebuilt with the engine's own MAC-01 rule and wording,
    // so the record stays coherent: a flipped state over unchanged values rendered a sentence
    // contradicting its own numbers (post-merge audit, 2026-11-11).
    const s = computed.signals.find((x) => x.id === 'MAC-01');
    if (!s?.values) throw new Error('no MAC-01 record to correct');
    const { ema20 } = s.values;
    const toActive = s.state !== 'ACTIVE';
    const close = ema20 * (toActive ? 0.99 : 1.01);
    const rsi = toActive ? Math.min(s.values.rsi, 45) : s.values.rsi;
    const gapPct = ((close - ema20) / ema20) * 100;
    s.values = { ...s.values, close, gapPct, rsi };
    s.state = close < ema20 && rsi < 50 ? 'ACTIVE' : 'INACTIVE';
    s.detail = `Broad dollar (DTWEXBGS) ${close.toFixed(4)} vs EMA20W ${ema20.toFixed(4)} (Δ ${gapPct.toFixed(3)}%); RSI ${rsi.toFixed(2)}`;
    if ('points' in s) s.points = s.state === 'ACTIVE' ? s.weight : 0;
    if ((s.state === 'ACTIVE') !== toActive) throw new Error('the MAC-01 correction did not flip');
  }
  // Weekly anchors move because the run re-fetches; monthly ones do not roll here
  // (deliberately — a late monthly print is a legitimate state, 5.462).
  let weekly = 0;
  for (const s of computed.signals) {
    if (s.anchorKind === 'weekly' && s.anchor && s.id !== 'ETF-01') {
      s.anchor = shiftDay(s.anchor, days);
      weekly += 1;
    }
  }

  // The ETF ledger (append-only) gains a row unless the leg failed or the pull
  // was incomplete (then the REAL refusal runs and the ledger must not change).
  const etfPath = p('etf-shares-weekly.jsonl');
  let etf = 0;
  let refusal = null;
  if (fs.existsSync(etfPath)) {
    const rows = readSnapshots(etfPath);
    if (etfDays !== null) {
      const nextAnchor = shiftDay(rows[rows.length - 1].anchor, etfDays);
      const base = [...rows].reverse().find(isCompleteSnapshot);
      if (etfIncomplete) {
        const before = fs.readFileSync(etfPath);
        const funds = Object.fromEntries(
          Object.entries(base.funds).map(([t, f]) => [t, { ...f, shares: null }])
        );
        const res = recordEtfSnapshot(
          { anchor: nextAnchor, funds },
          {
            attemptedAt: computed.computed_at,
            source: 'simulator',
            ledgerPath: etfPath,
            attemptsPath: p('etf-snapshot-attempts.jsonl'),
          }
        );
        if (res.outcome !== 'refused' || !fs.readFileSync(etfPath).equals(before))
          throw new Error(`an incomplete collection was not refused cleanly: ${res.outcome}`);
        refusal = { anchor: nextAnchor, complete: { anchor: nextAnchor, funds: base.funds } };
      } else {
        appendJsonlLine(etfPath, JSON.stringify({ ...base, anchor: nextAnchor }));
      }
    }
    etf = readSnapshots(etfPath).length;
  }

  // Re-score ETF-01 from the moved ledger with the real engine + archive seam,
  // then carry the score and band through the real scorer.
  const ledger = readSnapshots(etfPath);
  const at = new Date(computed.computed_at);
  // The PRODUCTION route (2026-10-18): `resolveEtfSignals` is what run.mjs and
  // compute-regime.mjs call, so the suspension applies here exactly as it will
  // on Monday. Calling `evaluateEtf01FromFlows` directly used to bypass it.
  const [etfRecord] = archiveSignals(
    [...resolveEtfSignals({ snapshots: ledger, manual: null }, at)],
    {
      etfSnapshotCount: ledgerCoverage(ledger).complete,
    }
  );
  computed.signals = computed.signals.map((s) => (s.id === 'ETF-01' ? etfRecord : s));
  const group = (prefix) => computed.signals.filter((s) => s.id.startsWith(prefix));
  const { groupTotals, score, band } = scoreSignals({
    btc: group('BTC-'),
    macro: group('MAC-'),
    etf: group('ETF-'),
    rel: group('REL-'),
  });
  computed.score = score;
  computed.regime_code = band.code;
  computed.group_totals = groupTotals;
  // Scenario J (5.875): the M2 print stops arriving. MAC-03's anchor is aged by whole months,
  // the fewest that put its row past `stale_after` by the panel's own rule (deriveDataStatus),
  // while the ETF ledger keeps pace, so the LOW week comes from M2 alone, through the blocking
  // step. (Scenario H reaches LOW only through the ETF row, already UNAVAILABLE.)
  if (m2Stale) {
    const m2 = computed.signals.find((s) => s.id === 'MAC-03');
    if (!m2?.anchor) throw new Error('no MAC-03 anchor to age');
    const original = m2.anchor;
    let stale = false;
    for (let k = 1; k <= 12 && !stale; k += 1) {
      const a = new Date(`${original.slice(0, 7)}-01T00:00:00Z`);
      a.setUTCMonth(a.getUTCMonth() - k);
      m2.anchor = a.toISOString().slice(0, 10);
      const row = deriveDataStatus(computed, readSnapshots(etfPath)).sources.find((s) =>
        s.source.includes('M2SL')
      );
      stale = row?.status === 'STALE';
    }
    if (!stale) throw new Error('MAC-03 could not be aged past its stale date');
  }
  const coherence = anchorCoherence(computed.signals);
  computed.anchor_spread_days = Number(coherence.spreadDays.toFixed(2));
  computed.anchor_warning = coherence.warning;
  fs.writeFileSync(p('computed.json'), `${JSON.stringify(computed, null, 2)}\n`);

  // The run archive gains the matching line — the growth that broke 2026-09-14.
  // The tolerant reader (lib/jsonl.mjs): a torn line in the real archive must
  // not crash the rehearsal or be taken for the last run.
  const archive = readJsonlTolerant(fs.readFileSync(p('run-archive.jsonl'), 'utf8'));
  const lastRun = archive[archive.length - 1];
  lastRun.run_at = computed.computed_at;
  lastRun.computed = { score, regime_code: band.code, group_totals: groupTotals };
  lastRun.signals = computed.signals;
  lastRun.anchor_spread_days = computed.anchor_spread_days;
  lastRun.anchor_warning = computed.anchor_warning;
  appendJsonlLine(p('run-archive.jsonl'), JSON.stringify(lastRun));

  return {
    refusal,
    weekly,
    archive: archive.length + 1,
    etf,
    etfState: etfRecord.state,
    etfVariant: etfRecord.values?.variant ?? null,
    score,
    band: band.code,
  };
}

